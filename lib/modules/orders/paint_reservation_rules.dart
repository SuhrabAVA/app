/// Правила учёта брони краски.
///
/// Бронь краски живёт в `order_paint_reservations` тремя числами:
///   * `reserved_qty`  — сколько заказ попросил;
///   * `used_qty`      — сколько уже израсходовано и списано со склада;
///   * `released_qty`  — сколько возвращено на склад (правка заказа, отмена).
///
/// Занимает остаток только непогашенная часть. Списанные граммы держать в броне
/// нельзя: они уже ушли со склада через `paints_writeoffs`, и вычитать их из
/// остатка второй раз — значит показывать нехватку там, где краска есть.
library;

/// Сколько граммов этой брони всё ещё занимает складской остаток.
///
/// Никогда не отрицательна: перерасход (`used_qty > reserved_qty`) — это уже
/// свершившийся факт склада, и в бронь он не возвращается со знаком минус.
///
/// Та же формула стоит на сервере в `sync_order_paint_reservations`:
/// `greatest(r.reserved_qty - r.used_qty - r.released_qty, 0)`. Клиент считал
/// иначе — по голому `reserved_qty`, — и его проверка была строже серверной.
/// Решает статус заказа именно клиент, поэтому расходились они в худшую
/// сторону: заказ вставал в «Ожидание материалов» при полном складе.
double outstandingPaintReservation({
  required double reservedQty,
  required double usedQty,
  required double releasedQty,
}) {
  final outstanding = reservedQty - usedQty - releasedQty;
  return outstanding > 0 ? outstanding : 0;
}
