/// Какое количество метров записать бумаге заказа при сохранении.
///
/// Приоритет один и тот же для основной бумаги и для дополнительных:
///
/// 1. [editedLength] — «Длина L» из формы. Это поле менеджер и правит, поэтому
///    оно главнее всего остального.
/// 2. [storedQuantity] — количество, уже сохранённое у материала. Берётся,
///    только когда поле пустое.
/// 3. [fallback] — общая длина заказа, последняя подстраховка для бумаги,
///    у которой своей длины не было никогда.
///
/// Регрессия, ради которой правило вынесено сюда: раньше приоритет был
/// обратный — сохранённое количество побеждало поле. Поле «Длина L» пишет
/// только `product.length`, а потребность в бумаге считается по
/// `material.quantity`, поэтому первое сохранённое значение застывало
/// навсегда: заказ с исправленной длиной 740 продолжал требовать прежние
/// 3900 м и висел в «Ожидании материалов» при полном складе.
double persistedPaperQuantity({
  required double editedLength,
  required double storedQuantity,
  double fallback = 0,
}) {
  if (editedLength > 0) return editedLength;
  if (storedQuantity > 0) return storedQuantity;
  return fallback > 0 ? fallback : 0;
}
