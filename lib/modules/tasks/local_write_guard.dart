/// Защита локальных записей от «отката» опоздавшим полным перечитом.
///
/// Провайдеры цеха живут так: действие уходит на сервер, ответ применяется к
/// локальному списку, экран перерисовывается. Параллельно с этим realtime и
/// страховочный поллинг дёргают ПОЛНЫЙ перечит (`select *` по всей таблице),
/// который затем делает `list..clear()..addAll(rows)`.
///
/// Если такой перечит СТАРТОВАЛ до записи, а завершился после неё, он
/// затирает уже применённый результат снимком, снятым до действия. Экран
/// откатывается в прошлое: помощник возвращается в бригаду, «Пересмена» снова
/// предлагается вместо «Продолжить пересмену». Сотрудник видит, что ничего не
/// произошло, и жмёт кнопку второй раз — в базе появляется вторая пересмена,
/// второе количество и второе списание бумаги (16.09, ЗК-2026.09.16-2:
/// 10:28:29 — 10 м, 10:28:44 — ещё 1 м).
///
/// Класс решает ровно это: помнит, что и когда было записано локально, и
/// после перечита возвращает на место те записи, которых читаемый снимок
/// заведомо не видел. Чистый, без БД и виджетов — поэтому проверяется тестами.
class LocalWriteGuard<T> {
  LocalWriteGuard({required this.idOf});

  /// Идентификатор строки: по нему запись накладывается на результат чтения.
  final String Function(T value) idOf;

  int _seq = 0;
  final Map<String, _GuardedWrite<T>> _writes = <String, _GuardedWrite<T>>{};

  /// Сколько локальных записей ещё не подтверждено чтением (для тестов).
  int get pendingCount => _writes.length;

  /// Метка начала чтения. Всё, что записано ПОСЛЕ неё, снимок не содержит.
  ///
  /// Счётчик монотонный и локальный: часы устройства в цеху врут (на складском
  /// ПК — на час), поэтому сравнивать времена нельзя.
  int beginFetch() => _seq;

  /// Запомнить локально применённую версию строки.
  void record(T value) {
    final id = idOf(value);
    if (id.isEmpty) return;
    _writes[id] = _GuardedWrite<T>(++_seq, value);
  }

  /// Забыть запись — например, строка удалена.
  void forget(String id) => _writes.remove(id);

  void clear() => _writes.clear();

  /// Накладывает на результат чтения локальные записи, сделанные во время
  /// этого чтения.
  ///
  /// [fetchToken] — значение [beginFetch] на момент старта чтения. Записи не
  /// новее токена снимок уже содержит: они забываются, чтобы не жить вечно.
  List<T> reconcile(List<T> fetched, int fetchToken) {
    if (_writes.isEmpty) return fetched;
    _writes.removeWhere((_, write) => write.seq <= fetchToken);
    if (_writes.isEmpty) return fetched;
    final result = List<T>.of(fetched);
    for (var i = 0; i < result.length; i++) {
      final write = _writes[idOf(result[i])];
      if (write != null) result[i] = write.value;
    }
    return result;
  }
}

class _GuardedWrite<T> {
  const _GuardedWrite(this.seq, this.value);

  final int seq;
  final T value;
}
