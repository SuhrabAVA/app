import 'task_model.dart';

/// Правило очереди рабочего места: когда следующее задание открывается.
///
/// Очередь рабочего места — это порядок заказов на ОДНОМ этапе. Она задаёт
/// приоритет («что брать следующим»), а не взаимное исключение: одно рабочее
/// место — это, как правило, несколько сотрудников, и пока один доводит
/// текущий заказ, второй должен иметь возможность взять следующий.
///
/// Поэтому предыдущее задание открывает следующее, как только его НАЧАЛИ, а
/// не когда завершили. Раньше для рабочих мест в режиме «Одиночная/
/// Совместная» (а он же и режим по умолчанию, см.
/// `parseWorkplaceExecutionMode`) действовало строгое правило «только после
/// завершения предыдущего»: заказ, который уже был в работе, запирал всю
/// очередь до самого закрытия этапа. Регрессия, ради которой правило
/// переписано: двое работают на этапе, первая продолжает текущий заказ,
/// вторая завершила своё участие и не может взять следующий — кнопка
/// «Начать» гаснет, хотя рабочее место свободно.
///
/// Завершённое задание и задание в «Проблеме» тоже открывают следующее: у них
/// статус отличен от [TaskStatus.waiting], то есть работа по ним уже шла.
bool hasWorkplaceQueueActivity(TaskModel task) {
  if (task.status != TaskStatus.waiting) return true;
  return task.comments.any(
    (c) => c.type == 'start' || c.type == 'resume' || c.type == 'user_done',
  );
}

/// Открыта ли позиция [index] в очереди рабочего места [queue].
///
/// Первая позиция открыта всегда; остальные — когда КАЖДОЕ стоящее раньше
/// задание уже начато (см. [hasWorkplaceQueueActivity]). Нетронутое задание
/// в середине очереди по-прежнему держит хвост: иначе порядок очереди
/// перестал бы что-либо значить.
bool isUnlockedByQueueOrder(List<TaskModel> queue, int index) {
  if (index <= 0) return true;
  for (var i = 0; i < index && i < queue.length; i++) {
    if (!hasWorkplaceQueueActivity(queue[i])) return false;
  }
  return true;
}
