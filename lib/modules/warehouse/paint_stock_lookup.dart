/// Фактический остаток краски на складе по её названию.
///
/// ЗАЧЕМ
/// В задании рабочий видит, сколько краски положено на заказ («200 г»), но не
/// видит, сколько её вообще есть. Отсюда вопросы «хватит ли» и походы на склад
/// посреди смены. Рядом с плановым расходом показывается ПОЛНЫЙ остаток
/// карточки — всё, что физически стоит на полке: и свободное, и занятое
/// бронями, и неприкасаемый запас. Это ответ на вопрос «сколько есть», а не
/// «сколько мне дадут».
///
/// СВЕРКА ПО ИМЕНИ
/// У строки краски в заказе может не быть ссылки на карточку склада — часть
/// красок вписана текстом. Поэтому сверяем по нормализованному названию, тем
/// же правилом, что и сервер (`lower(trim(description))` плюс схлопывание
/// пробелов).
library;

import 'tmc_model.dart';

/// Нормализация названия краски для сопоставления.
String normalizePaintLookupName(String value) =>
    value.trim().toLowerCase().replaceAll(RegExp(r'\s+'), ' ');

/// Название → остаток на складе.
///
/// Тёзки складываются: две карточки с одним названием — это одна краска,
/// заведённая дважды, и показывать рабочему только одну из них значило бы
/// занижать остаток.
Map<String, double> paintStockIndex(Iterable<TmcModel> paints) {
  final index = <String, double>{};
  for (final paint in paints) {
    final key = normalizePaintLookupName(paint.description);
    if (key.isEmpty) continue;
    index[key] = (index[key] ?? 0) + paint.quantity;
  }
  return index;
}

/// Остаток по названию; `null` — карточки с таким названием на складе нет.
///
/// `null` и ноль различаются намеренно: «нет карточки» и «есть, но пусто» —
/// разные новости, и показывать «(0 г)» там, где краска просто не заведена,
/// значит врать.
double? paintStockFor(Map<String, double> index, String name) =>
    index[normalizePaintLookupName(name)];
