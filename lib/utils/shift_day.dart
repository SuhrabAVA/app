/// День смены, к которому относится момент времени.
///
/// Ночная смена начинается вечером и заканчивается утром следующих суток,
/// поэтому всё, что произошло до 06:00, принадлежит смене предыдущего
/// календарного дня. Правило общее для расчёта зарплаты (подсчёт смен и
/// определение статуса дня) и для границ периодов статуса: если они
/// разойдутся, день на стыке будет оплачен по одному правилу, а посчитан
/// по другому.
library;

/// Начало суток смены для момента [moment].
DateTime shiftDayOf(DateTime moment) {
  final base = DateTime(moment.year, moment.month, moment.day);
  return moment.hour < 6 ? base.subtract(const Duration(days: 1)) : base;
}

/// Первый день следующей смены после [moment].
///
/// Граница «со следующей смены»: текущий день смены целиком остаётся за
/// прежним состоянием, новое начинается со следующего дня.
DateTime nextShiftDayAfter(DateTime moment) =>
    shiftDayOf(moment).add(const Duration(days: 1));
