-- Задача заказа на рабочем месте — одна. Схлопываем дубли и запрещаем новые.
--
-- ЗАЧЕМ
-- Заказ двоился в списке рабочего места: у ЗК-2026.08.31-5 (Hardees) по две
-- строки задачи на «Флексопечать», «Автомат маленький» и «Упаковку». Причина —
-- гонка при запуске заказа: OrderQueueSyncService создаёт задачи по схеме
-- «прочитал существующие → вставил недостающие», без транзакции и без
-- уникального ключа. Два запуска, разошедшиеся на сотню миллисекунд, оба
-- видят «задач нет» и оба их создают. Отметки времени это подтверждают: строки
-- вставлялись вперемежку, 08:02:30.612 / .760 / .859 / 31.008 / .111 / .272.
--
-- Клиент со своей стороны уже защищён (повторный запуск того же заказа
-- отклоняется), но защита в приложении не закрывает гонку между устройствами.
-- Единственный надёжный запрет — уникальный ключ в базе.
--
-- ЧТО СХЛОПЫВАЕМ
-- Всего 22 пары, ни одной тройки. В каждой паре работа лежит только на одной
-- строке, вторая — пустой близнец: у него либо ноль комментариев, либо один
-- служебный, тогда как у рабочей строки их 6, 9 или 17. Правило удаления
-- отсюда и берётся: оставляем строку с БОЛЬШИМ числом комментариев, при
-- равенстве — созданную раньше. Так ни одна отметка времени и количества,
-- уходящая в аналитику и зарплату, не теряется.
--
-- 16 пар — на завершённых заказах начала августа (обе строки closed), 6 — на
-- двух заказах в производстве: ЗК-2026.08.28-6 и ЗК-2026.08.31-5. У последнего
-- все три близнеца пустые и в статусе waiting.
--
-- ПРОВЕРКА ПЕРЕД ПРИМЕНЕНИЕМ (должна вернуть 0 строк):
--   select order_id, stage_id, count(*)
--     from tasks group by order_id, stage_id having count(*) > 2;

begin;

-- 1. Удаляем пустых близнецов ------------------------------------------------

with ranked as (
  select
    t.id,
    row_number() over (
      partition by t.order_id, t.stage_id
      order by
        jsonb_array_length(public.task_comments_to_array(t.comments)) desc,
        t.created_at asc,
        t.id asc
    ) as rn
  from public.tasks t
)
delete from public.tasks t
using ranked r
where t.id = r.id
  and r.rn > 1;

-- 2. Запрещаем повторное появление -------------------------------------------
--
-- Уникальность именно по (order_id, stage_id), а не по группе этапов:
-- у переключаемых этапов в одной группе несколько РАЗНЫХ рабочих мест
-- («Высечка А1» и «Высечка А2», три варианта склейки дна), и каждому из них
-- своя строка задачи положена.

create unique index if not exists tasks_order_stage_uniq
  on public.tasks (order_id, stage_id);

commit;

comment on index public.tasks_order_stage_uniq is
  'Одна задача на пару «заказ + рабочее место». Закрывает гонку двойного '
  'запуска заказа: без ключа два одновременных вызова OrderQueueSyncService '
  'создавали по комплекту задач каждый, и заказ двоился в списке цеха.';
