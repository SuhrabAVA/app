-- ============================================================================
-- Целостность очереди рабочих мест (2026-09-09)
--
-- Что чинит
-- ---------
-- Заказ TOO RAW нельзя было поднять в очереди Листорезки: перетаскивание
-- срабатывало, а строка возвращалась вниз. Причина — ДВЕ строки очереди на
-- один и тот же заказ+этап:
--
--   позиция 28  task_id f0d2c621…  ← задачи с таким id нет, она удалена
--   позиция 47  task_id 44aaa1e7…  ← настоящая задача
--
-- Показ (`priorityOfEntry`) находил строку по точному ключу и брал позицию 47.
-- Перестановка (`reorderedQueueKeys` → `preferredPosition`) сводила дубли по
-- смыслу и при равенстве выбирала МЕНЬШУЮ позицию, то есть строку-призрак 28.
-- Номер уходил на мёртвую строку, живая уезжала в хвост, и экран показывал
-- заказ там же, где он был.
--
-- Откуда брались призраки
-- -----------------------
-- OrderQueueSyncService удаляет и пересоздаёт незапущенные задачи с новыми id
-- (правка маршрута, чистка дублей). Строки очереди при этом никто не трогал:
-- внешнего ключа не было, `task_id` лежал текстом. Чистка была только при
-- удалении ЗАКАЗА целиком (`_cleanupProductionQueueState`), а при пересборке
-- маршрута — нет. К сегодняшнему дню накопилось 13 таких строк.
--
-- Что делает миграция
-- -------------------
-- 1. Убирает строки на несуществующие задачи. Проверено: все 4 задвоенных
--    элемента — это пары «призрак + живая», после чистки дублей не остаётся.
-- 2. Переводит `task_id` в uuid и вешает внешний ключ с каскадом. Теперь
--    удаление задачи само уносит её строку очереди — накопить призраков
--    больше нельзя.
-- 3. Запрещает второй строке появиться: уникальность по
--    (рабочее место, заказ, этап, группа этапов).
--
-- Порядок важен: сначала данные, потом ограничения — иначе они не встанут.
-- ============================================================================

begin;

-- ─── 1. Строки на удалённые задачи ──────────────────────────────────────────

-- Строки без task_id оставляем: их заводит рабочее пространство, когда задача
-- ещё не создана, и они законны.
delete from public.workplace_queue_positions q
 where q.task_id is not null
   and not exists (
     select 1 from public.tasks t where t.id::text = q.task_id
   );

-- ─── 2. Тип и внешний ключ ──────────────────────────────────────────────────

-- Все оставшиеся значения — корректные uuid (проверено перед миграцией:
-- ни одной строки, не подходящей под формат).
alter table public.workplace_queue_positions
  alter column task_id type uuid using nullif(btrim(task_id), '')::uuid;

alter table public.workplace_queue_positions
  drop constraint if exists workplace_queue_positions_task_id_fkey;

alter table public.workplace_queue_positions
  add constraint workplace_queue_positions_task_id_fkey
  foreign key (task_id) references public.tasks (id) on delete cascade;

-- ─── 3. Один элемент — одна строка ──────────────────────────────────────────
--
-- coalesce вместо голой колонки: у части строк stage_group_key пуст, а NULL в
-- обычном уникальном индексе не сравнивается сам с собой — дубли прошли бы
-- насквозь именно там, где их и наплодило.

drop index if exists workplace_queue_positions_item_uniq;

create unique index workplace_queue_positions_item_uniq
  on public.workplace_queue_positions (
    workplace_id, order_id, stage_id, coalesce(stage_group_key, '')
  );

commit;
