-- Обязательные блоки заказа + понятные названия блоков.
--
-- ЗАЧЕМ
-- Заказ уходил в «Готов к запуску», не имея ни одной бумаги. Причина не в
-- ошибке проверки, а в её природе: проверка обеспеченности отвечает на вопрос
-- «хватает ли того, что выбрано», и пустой заказ проходит её как «нехватки
-- нет». Нужен второй вопрос — «а всё ли вписано», — и ответ на него зависит от
-- типа продукта: пакету нужна ручка, листам она не нужна.
--
-- Колонка product_type_form_blocks.is_required заведена ещё миграцией
-- 20260806 «авансом, до следующей фазы не читается». Эта фаза наступила:
-- редактор её показывает, пересчёт статусов читает.
--
-- ЧТО ЗДЕСЬ ДЕЛАЕТСЯ
--   1. can_hide — блок, который нельзя выключить, но можно потребовать;
--   2. блок «Основная бумага» — раньше его в справочнике не было вовсе;
--   3. названия блоков переписаны на понятные сотруднику.

-- ═══════════════════════════════════════════════════════════════════════════
-- 1. Блоки, которые нельзя скрыть
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Миграция 20260806 держала в справочнике только блоки, видимостью которых
-- можно управлять: «Блоки, без которых заказ не существует (дата, заказчик,
-- тип, тираж, размеры, основной материал), сюда намеренно не входят — их
-- скрытие сломало бы форму, а не настроило её».
--
-- Обязательность ломает это разделение: основную бумагу скрывать нельзя, а
-- требовать — ровно то, чего просили. Поэтому справочник расширяется, но у
-- таких строк появляется признак «выключатель недоступен».

alter table public.order_form_blocks
  add column if not exists can_hide boolean not null default true;

comment on column public.order_form_blocks.can_hide is
  'Можно ли выключить блок в форме заказа. false — блок показывается всегда, '
  'редактор прячет у него переключатель видимости, но флаг «обязателен» '
  'остаётся доступным. Так в справочник попадают поля, без которых форма не '
  'работает, но требовать заполнения которых техлид всё равно должен.';

-- ═══════════════════════════════════════════════════════════════════════════
-- 2. Основная бумага
-- ═══════════════════════════════════════════════════════════════════════════
--
-- sort_order = 5: в списке блоков она встаёт первой, перед картоном. Именно с
-- неё техлид начинает читать, и именно её отсутствие привело к этой миграции.

insert into public.order_form_blocks (code, title, affects_input, sort_order, can_hide)
values ('material', 'Основная бумага', null, 5, false)
on conflict (code) do update
  set title = excluded.title,
      sort_order = excluded.sort_order,
      can_hide = excluded.can_hide;

-- ═══════════════════════════════════════════════════════════════════════════
-- 3. Понятные названия
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Прежние подписи были внутренним жаргоном: «Кол-во по БЛ» не расшифровывалось
-- даже техлидом. Название обязано читаться без подсказки — подсказка объясняет
-- ПОСЛЕДСТВИЯ, а не термин.

update public.order_form_blocks set title = 'Количество в строке бумаги (К)'
 where code = 'bl_quantity';
update public.order_form_blocks set title = 'Рулон в размерах продукта'
 where code = 'roll';
update public.order_form_blocks set title = 'Дополнительные бумаги'
 where code = 'extra_papers';
update public.order_form_blocks set title = 'Печатная форма'
 where code = 'form';
update public.order_form_blocks set title = 'PDF заказа'
 where code = 'pdf';
update public.order_form_blocks set title = 'Тип ручки'
 where code = 'handle';

-- ═══════════════════════════════════════════════════════════════════════════
-- 4. Флаг обязательности вводится в работу
-- ═══════════════════════════════════════════════════════════════════════════

comment on column public.product_type_form_blocks.is_required is
  'Без этого блока заказ не уходит в «Готов к запуску»: пересчёт статусов '
  'возвращает его в черновик и пишет, чего не хватает. Отсутствие строки = не '
  'обязателен. У скрытого блока флаг не действует — требовать заполнить поле, '
  'которого нет в форме, значило бы запереть заказ навсегда; правило '
  'продублировано в ProductTypeSettings.isBlockRequired, чтобы старая строка '
  '«скрыт и обязателен» никого не заперла.';
