-- Стартовые требования к блокам: основная бумага обязательна везде.
--
-- ЗАЧЕМ ИМЕННО ЭТО И ТОЛЬКО ЭТО
-- Заказ без единой бумаги доезжал до «Готов к запуску» — с этого начался весь
-- механизм обязательности. Бумага нужна любому изделию, условий тут нет, и
-- поставить требование можно, ничего не зная о конкретном производстве.
--
-- Остальные блоки НЕ проставляются намеренно. «Обязателен» — это запрет, и
-- проставленный наугад он запирает заказы в черновиках у всей смены. Что из
-- перечисленного ниже включать, решает производство; заготовки с разбором
-- лежат в конце файла закомментированными.
--
-- ПОЧЕМУ ПРЯМО В ОПУБЛИКОВАННУЮ ВЕРСИЮ
-- Обычная правка идёт через черновик и публикацию. Здесь это невозможно:
-- черновик — вещь техлида, и создавать его миграцией значит подсунуть человеку
-- незаконченную правку, о которой он не просил. Прецедент тот же, что у
-- 20260806: стартовые значения кладутся в действующую версию.

-- ═══════════════════════════════════════════════════════════════════════════
-- Основная бумага — обязательна для всех типов продукта
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Идемпотентно: повторный прогон ничего не меняет. Строку заводим и там, где
-- её не было (таблица держит только отклонения от умолчания), — is_visible
-- остаётся true, блок всё равно неотключаемый (can_hide = false).

insert into public.product_type_form_blocks
       (config_id, block_code, is_visible, is_required)
select cfg.id, 'material', true, true
  from public.product_type_configs cfg
 where cfg.status = 'published'
on conflict (config_id, block_code) do update
  set is_required = true,
      is_visible = true;

