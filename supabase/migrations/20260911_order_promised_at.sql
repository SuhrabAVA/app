-- Обещанный срок завершения, назначенный производством.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ПРАВКА due_date
-- `due_date` — срок, о котором договорились с заказчиком. Его ставит менеджер
-- при оформлении, по нему считаются просрочки и претензии, и переписывать его
-- из цеха нельзя: тогда исчезнет сам факт, что срок сдвинули.
--
-- `promised_at` — когда производство обещает закончить на самом деле. Его
-- ставит сотрудник в МУПЗ, менять можно сколько угодно раз, и каждая правка
-- пишется в историю заказа с автором.
--
-- Показ идёт по `promised_at`, если он задан, иначе по `due_date`. Разницу
-- видно глазом: обычный срок — цветные цифры на белом, назначенный вручную —
-- белые цифры в цветной рамке. Так в любом модуле понятно, смотришь ты на
-- договорённость с заказчиком или на обещание цеха.
--
-- ВРЕМЯ, А НЕ ТОЛЬКО ДАТА
-- timestamptz, потому что сотрудник называет и час: «завтра к 14:00». У
-- `due_date` время не спрашивают — там граница дня, и она достраивается
-- правилом deadlineFromDueDate.

alter table public.orders
  add column if not exists promised_at timestamptz;

comment on column public.orders.promised_at is
  'Когда производство обещает закончить заказ. Назначается сотрудником в '
  'МУПЗ, меняется сколько угодно раз, каждая правка — запись в истории '
  'заказа. НЕ заменяет due_date: тот остаётся сроком заказчика, иначе факт '
  'сдвига срока исчез бы. Показ везде идёт по promised_at, если он задан.';
