import 'package:flutter_test/flutter_test.dart';
import 'package:sheet_clone/modules/orders/material_shortage_lines.dart';

/// Нехватка материалов — коротким списком на карточке заказа.
///
/// До этого карточка показывала одну позицию из пяти: текст собран в одну
/// строку и обрезался на первой. Сотрудник шёл на склад за неполным списком.

void main() {
  group('parseShortageLines', () {
    test('бумага разбирается в «Б: имя — сколько»', () {
      final lines = parseShortageLines(
        'Не хватает 3382.37 м бумаги «Белый крафт Илим»: '
        'доступно 6517.63 из 9900.',
      );

      expect(lines, hasLength(1));
      expect(lines.single.kind, 'Б');
      expect(lines.single.name, 'Белый крафт Илим');
      expect(lines.single.amount, '3382.37 м');
      expect(lines.single.text, 'Б: Белый крафт Илим — 3382.37 м');
    });

    test('краска разбирается в «К: имя — сколько»', () {
      final lines = parseShortageLines(
        'Не хватает 35000 г краски «285 Синий»: свободного остатка нет '
        '(на складе 0 г, из них 5000 г неприкасаемы).',
      );

      expect(lines.single.text, 'К: 285 Синий — 35000 г');
    });

    test('несколько позиций — несколько строк, в порядке сообщения', () {
      final lines = parseShortageLines(
        'Не хватает 3382.37 м бумаги «Белый крафт Илим»: доступно 6517.63 из '
        '9900. Не хватает 1200 м бумаги «Крафт 90»: на складе нет. '
        'Не хватает 35000 г краски «285 Синий»: свободного остатка нет. '
        'Не хватает 2000 г краски «192D Красный»: доступно 1 из 2001.',
      );

      expect(
        lines.map((l) => l.text),
        [
          'Б: Белый крафт Илим — 3382.37 м',
          'Б: Крафт 90 — 1200 м',
          'К: 285 Синий — 35000 г',
          'К: 192D Красный — 2000 г',
        ],
      );
    });

    test('краски нет на складе — закупка обеими половинами', () {
      // Снабженцу везти и то и другое одной закупкой, поэтому в строке обе
      // половины: на заказ и обязательный запас.
      final lines = parseShortageLines(
        'Краски «Белила» нет на складе. Нужно заказать 6000 г '
        '(1000 г на заказ + 5000 г обязательного запаса).',
      );

      expect(lines.single.text, 'К: Белила — 1000 г + 5000 г');
    });

    test('просевший обязательный запас входит в строку своей краски', () {
      final lines = parseShortageLines(
        'Не хватает 35000 г краски «285 Синий»: свободного остатка нет '
        '(на складе 0 г, из них 5000 г неприкасаемы). '
        'Обязательный запас просел: нужно пополнить 5000 г. '
        'Не хватает 2000 г краски «192D Красный»: доступно 1 из 2001.',
      );

      expect(
        lines.map((l) => l.text),
        [
          'К: 285 Синий — 35000 г + 5000 г',
          // Кусается: заметка о запасе приписана ПЕРВОЙ краске и не должна
          // перетечь во вторую.
          'К: 192D Красный — 2000 г',
        ],
      );
    });

    test('бумага запаса не получает', () {
      final lines = parseShortageLines(
        'Не хватает 1200 м бумаги «Крафт 90»: на складе нет. '
        'Не хватает 35000 г краски «285 Синий»: свободного остатка нет. '
        'Обязательный запас просел: нужно пополнить 5000 г.',
      );

      expect(lines.first.text, 'Б: Крафт 90 — 1200 м');
      expect(lines.last.text, 'К: 285 Синий — 35000 г + 5000 г');
    });

    test('неразобранный текст не теряется', () {
      // «Не выбрана краска.» приписана к общему тексту и без этой ветки
      // исчезла бы из списка — а это причина, по которой заказ стоит.
      final lines = parseShortageLines(
        'Не выбрана краска. Не хватает 1200 м бумаги «Крафт 90»: '
        'на складе нет.',
      );

      expect(lines, hasLength(2));
      expect(lines.first.parsed, isFalse);
      expect(lines.first.text, 'Не выбрана краска.');
      expect(lines.last.text, 'Б: Крафт 90 — 1200 м');
    });

    test('совсем незнакомый текст отдаётся как есть', () {
      final lines = parseShortageLines('Материал не выбран в заказе.');

      expect(lines.single.parsed, isFalse);
      expect(lines.single.text, 'Материал не выбран в заказе.');
    });

    test('пустое сообщение — пустой список', () {
      expect(parseShortageLines(null), isEmpty);
      expect(parseShortageLines('   '), isEmpty);
    });
  });
}
